const createItems = (prefix, contents) => contents.map((content, index) => ({
  id: `${prefix}${String(index + 1).padStart(2, "0")}`,
  content,
}));

function buildExampleWarehouse({ id, name, updatedAt, items, shelfDefinitions, temporaryIds }) {
  const temporarySet = new Set(temporaryIds);
  const shelfByItemId = new Map(
    shelfDefinitions.flatMap((shelf) => shelf.itemIds.map((itemId) => [itemId, shelf.id])),
  );
  const pinecones = items.map((item, index) => {
    const isTemporary = temporarySet.has(item.id);
    return {
      id: item.id,
      content: item.content,
      status: isTemporary ? "temp" : "shelved",
      shelfId: isTemporary ? "" : shelfByItemId.get(item.id),
      tags: [],
      isFeatured: !isTemporary && index % 6 === 0,
      createdAt: `08-${String(20 - (index % 8)).padStart(2, "0")} ${String(9 + (index % 10)).padStart(2, "0")}:${index % 2 ? "35" : "10"}`,
    };
  });
  const itemById = new Map(pinecones.map((pinecone) => [pinecone.id, pinecone]));
  const shelves = shelfDefinitions.map(({ id: shelfId, title, summary }) => ({
    id: shelfId,
    name: title,
    description: summary,
  }));
  const sections = shelfDefinitions.map(({ id: shelfId, title, summary, itemIds }) => ({
    shelfId,
    heading: title,
    summary,
    bullets: itemIds.map((itemId) => ({
      text: itemById.get(itemId).content,
      pineconeIds: [itemId],
    })),
  }));

  return {
    id,
    name,
    updatedAt,
    tempLimit: 5,
    pinecones,
    shelves,
    reviewDocument: { title: name, sections },
  };
}

